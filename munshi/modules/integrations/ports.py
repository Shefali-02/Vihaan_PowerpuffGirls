"""Ports for government / financial systems. Munshi makes NO real government calls in this MVP.

Every adapter output carries "mode": "MOCK"; asking for LIVE raises NotEnabledError.
Nothing here implies integration with or approval by GSTN, CBDT, MCA, EPFO, RBI or any other body.
"""
from __future__ import annotations

from typing import Protocol


class GstPort(Protocol):
    def get_gstr2b(self, gstin: str, period: str) -> dict: ...
    def prepare_gstr1(self, gstin: str, period: str, summary: dict) -> dict: ...
    def prepare_gstr3b(self, gstin: str, period: str, summary: dict) -> dict: ...
    def submit(self, return_type: str, payload: dict) -> dict: ...


class ItdPort(Protocol):  # Income-tax (TDS / 26AS style data)
    def get_26as(self, pan: str, assessment_year: str) -> dict: ...
    def prepare_tds_return(self, tan: str, quarter: str, deductions: list[dict]) -> dict: ...


class McaPort(Protocol):  # Company filings
    def get_company_master(self, cin: str) -> dict: ...
    def prepare_aoc4(self, cin: str, financial_year: str, financials: dict) -> dict: ...


class EpfoPort(Protocol):  # Provident fund
    def prepare_ecr(self, establishment_id: str, wage_month: str, members: list[dict]) -> dict: ...


class NswsPort(Protocol):  # Business approvals / registrations
    def list_registrations(self, pan: str) -> dict: ...


class AaPort(Protocol):  # Account Aggregator (bank statements with consent)
    def request_consent(self, customer_vua: str, fi_types: list[str], purpose: str) -> dict: ...
    def fetch_statements(self, consent_id: str) -> dict: ...
